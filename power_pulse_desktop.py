"""
Power Pulse Desktop App (Modern UI with CustomTkinter)
=========================================================
A polished native desktop GUI for the Power Pulse prediction system.
Run with: python power_pulse_desktop.py

Requires: power_pulse_model.pkl, feature_cols.pkl, power_pulse_features.csv
(all generated by train_model.py) to be in the same folder.

Install once: pip install customtkinter matplotlib pandas scikit-learn joblib
"""

import customtkinter as ctk
import pandas as pd
import joblib
import matplotlib
matplotlib.use("TkAgg")
from matplotlib.figure import Figure
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg

ctk.set_appearance_mode("dark")
ctk.set_default_color_theme("blue")

# ----------------------------
# Load model + data once at startup
# ----------------------------
model = joblib.load("power_pulse_model.pkl")
feature_cols = joblib.load("feature_cols.pkl")
df = pd.read_csv("power_pulse_features.csv", parse_dates=["timestamp"])
CITY_LIST = sorted(df["city"].unique())

CARD_COLOR = "#1e293b"
BG_COLOR = "#0f172a"
ACCENT = "#38bdf8"
TEXT_MUTED = "#94a3b8"


class PowerPulseApp(ctk.CTk):
    def __init__(self):
        super().__init__()
        self.title("Power Pulse — Bangalore Power Cut Prediction")
        self.geometry("1000x780")
        self.configure(fg_color=BG_COLOR)

        self.city_var = ctk.StringVar(value=CITY_LIST[0])
        self.city_df = df[df["city"] == CITY_LIST[0]].reset_index(drop=True)
        self.row_idx = ctk.IntVar(value=len(self.city_df) - 500)

        self._build_header()
        self._build_metrics()
        self._build_risk_card()
        self._build_slider()
        self._build_chart()
        self._build_footer()

        self.update_display()

    # ---------- UI sections ----------
    def _build_header(self):
        header = ctk.CTkFrame(self, fg_color="transparent")
        header.pack(fill="x", padx=30, pady=(25, 10))

        ctk.CTkLabel(header, text="⚡ Power Pulse", font=ctk.CTkFont(size=28, weight="bold"),
                     text_color=ACCENT).pack(anchor="w")
        ctk.CTkLabel(header, text="Predicting power cuts 1 hour before they happen",
                     font=ctk.CTkFont(size=13), text_color=TEXT_MUTED).pack(anchor="w")

        city_row = ctk.CTkFrame(header, fg_color="transparent")
        city_row.pack(anchor="w", pady=(10, 0))
        ctk.CTkLabel(city_row, text="City:", font=ctk.CTkFont(size=13, weight="bold"),
                     text_color="white").pack(side="left", padx=(0, 8))
        self.city_menu = ctk.CTkOptionMenu(city_row, values=list(CITY_LIST), variable=self.city_var,
                                            command=self.on_city_change, fg_color=CARD_COLOR,
                                            button_color=ACCENT, width=160)
        self.city_menu.pack(side="left")

    def _build_metrics(self):
        frame = ctk.CTkFrame(self, fg_color="transparent")
        frame.pack(fill="x", padx=30, pady=10)
        frame.grid_columnconfigure((0, 1, 2), weight=1)

        self.voltage_card, self.voltage_val = self._metric_card(frame, "VOLTAGE", "-- V", 0)
        self.freq_card, self.freq_val = self._metric_card(frame, "FREQUENCY", "-- Hz", 1)
        self.load_card, self.load_val = self._metric_card(frame, "LOAD", "-- kW", 2)

    def _metric_card(self, parent, label, value, col):
        card = ctk.CTkFrame(parent, fg_color=CARD_COLOR, corner_radius=14)
        card.grid(row=0, column=col, padx=8, sticky="nsew")
        ctk.CTkLabel(card, text=label, font=ctk.CTkFont(size=11, weight="bold"),
                     text_color=TEXT_MUTED).pack(pady=(16, 2))
        val_lbl = ctk.CTkLabel(card, text=value, font=ctk.CTkFont(size=24, weight="bold"),
                                text_color="white")
        val_lbl.pack(pady=(0, 16))
        return card, val_lbl

    def _build_risk_card(self):
        self.risk_card = ctk.CTkFrame(self, fg_color=CARD_COLOR, corner_radius=14)
        self.risk_card.pack(fill="x", padx=30, pady=10)

        ctk.CTkLabel(self.risk_card, text="POWER CUT RISK — NEXT 1 HOUR",
                     font=ctk.CTkFont(size=12, weight="bold"), text_color=TEXT_MUTED).pack(pady=(18, 4))

        self.risk_label = ctk.CTkLabel(self.risk_card, text="--", font=ctk.CTkFont(size=20, weight="bold"))
        self.risk_label.pack(pady=(0, 10))

        self.risk_bar = ctk.CTkProgressBar(self.risk_card, width=700, height=14, corner_radius=7)
        self.risk_bar.pack(pady=(0, 20))
        self.risk_bar.set(0)

    def _build_slider(self):
        frame = ctk.CTkFrame(self, fg_color="transparent")
        frame.pack(fill="x", padx=30, pady=10)

        ctk.CTkLabel(frame, text="Simulate a reading — scrub through the timeline",
                     font=ctk.CTkFont(size=12), text_color=TEXT_MUTED).pack(anchor="w", pady=(0, 6))

        self.slider = ctk.CTkSlider(frame, from_=0, to=len(self.city_df) - 1,
                                     variable=self.row_idx, command=lambda v: self.update_display(),
                                     progress_color=ACCENT, button_color=ACCENT)
        self.slider.pack(fill="x")

        self.time_label = ctk.CTkLabel(frame, text="", font=ctk.CTkFont(size=12, weight="bold"),
                                        text_color=ACCENT)
        self.time_label.pack(anchor="w", pady=(8, 0))

    def _build_chart(self):
        chart_card = ctk.CTkFrame(self, fg_color=CARD_COLOR, corner_radius=14)
        chart_card.pack(fill="both", expand=True, padx=30, pady=10)

        self.tabs = ctk.CTkTabview(chart_card, fg_color=CARD_COLOR,
                                    segmented_button_selected_color=ACCENT,
                                    segmented_button_selected_hover_color=ACCENT)
        self.tabs.pack(fill="both", expand=True, padx=10, pady=10)

        for tab_name in ["Voltage", "Frequency", "Load", "Risk Over Time", "Outages by Hour"]:
            self.tabs.add(tab_name)

        # Live trend charts (update with the slider)
        self.fig_voltage, self.ax_voltage, self.canvas_voltage = self._make_canvas(self.tabs.tab("Voltage"))
        self.fig_freq, self.ax_freq, self.canvas_freq = self._make_canvas(self.tabs.tab("Frequency"))
        self.fig_load, self.ax_load, self.canvas_load = self._make_canvas(self.tabs.tab("Load"))
        self.fig_risk, self.ax_risk, self.canvas_risk = self._make_canvas(self.tabs.tab("Risk Over Time"))

        # Static chart (computed once — doesn't depend on the slider)
        self.fig_hourly, self.ax_hourly, self.canvas_hourly = self._make_canvas(self.tabs.tab("Outages by Hour"))
        self._draw_outages_by_hour()

    def _make_canvas(self, parent):
        fig = Figure(figsize=(9, 3), dpi=100, facecolor=CARD_COLOR)
        ax = fig.add_subplot(111)
        canvas = FigureCanvasTkAgg(fig, master=parent)
        canvas.get_tk_widget().pack(fill="both", expand=True, padx=10, pady=10)
        return fig, ax, canvas

    def _style_ax(self, ax, title):
        ax.set_facecolor(CARD_COLOR)
        ax.tick_params(colors=TEXT_MUTED, labelsize=8)
        ax.set_title(title, color="white", fontsize=11, loc="left")
        for spine in ax.spines.values():
            spine.set_color("#334155")

    def _draw_outages_by_hour(self):
        # Precompute once: how many outage readings happened in each hour of day
        hourly_counts = self.city_df[self.city_df["power_cut"] == 1]["hour"].value_counts().sort_index()
        all_hours = list(range(24))
        counts = [hourly_counts.get(h, 0) for h in all_hours]

        self.ax_hourly.clear()
        bar_colors = [ACCENT if h in range(18, 21) else "#475569" for h in all_hours]
        self.ax_hourly.bar(all_hours, counts, color=bar_colors)
        self._style_ax(self.ax_hourly, f"Historical Outages by Hour of Day - {self.city_var.get()} (peak hours highlighted)")
        self.ax_hourly.set_xticks(all_hours)
        self.ax_hourly.set_xlabel("Hour", color=TEXT_MUTED, fontsize=9)
        self.fig_hourly.tight_layout()
        self.canvas_hourly.draw()

    def _build_footer(self):
        ctk.CTkLabel(self, text="Model: Random Forest  •  Data: simulated from typical load-shedding patterns per city",
                     font=ctk.CTkFont(size=10), text_color=TEXT_MUTED).pack(pady=(0, 15))

    def on_city_change(self, city):
        self.city_df = df[df["city"] == city].reset_index(drop=True)
        self.slider.configure(to=len(self.city_df) - 1)
        self.row_idx.set(len(self.city_df) - 500)
        self._draw_outages_by_hour()
        self.update_display()

    # ---------- Logic ----------
    def update_display(self):
        idx = int(self.row_idx.get())
        row = self.city_df.iloc[idx]

        self.voltage_val.configure(text=f"{row['voltage']:.1f} V")
        self.freq_val.configure(text=f"{row['frequency']:.2f} Hz")
        self.load_val.configure(text=f"{row['load_kw']:.2f} kW")
        self.time_label.configure(text=f"🕐 {row['timestamp']}")

        X_current = row[feature_cols].values.reshape(1, -1)
        risk_prob = model.predict_proba(X_current)[0][1]
        risk_pct = round(risk_prob * 100, 1)

        self.risk_bar.set(risk_prob)
        if risk_pct >= 70:
            color, text = "#ef4444", f"🔴 HIGH RISK — {risk_pct}% chance of a power cut"
            self.risk_bar.configure(progress_color="#ef4444")
        elif risk_pct >= 40:
            color, text = "#f59e0b", f"🟡 MODERATE RISK — {risk_pct}% chance of a power cut"
            self.risk_bar.configure(progress_color="#f59e0b")
        else:
            color, text = "#22c55e", f"🟢 LOW RISK — {risk_pct}% chance of a power cut"
            self.risk_bar.configure(progress_color="#22c55e")
        self.risk_label.configure(text=text, text_color=color)

        # Update trend charts (shared surrounding window)
        window_start = max(0, idx - 30)
        window_end = min(len(self.city_df), idx + 10)
        trend = self.city_df.iloc[window_start:window_end]

        self._draw_line(self.ax_voltage, self.fig_voltage, self.canvas_voltage,
                         trend["timestamp"], trend["voltage"], "Voltage (V)",
                         "Voltage Trend (surrounding window)", ACCENT)

        self._draw_line(self.ax_freq, self.fig_freq, self.canvas_freq,
                         trend["timestamp"], trend["frequency"], "Frequency (Hz)",
                         "Frequency Trend (surrounding window)", "#a78bfa")

        self._draw_line(self.ax_load, self.fig_load, self.canvas_load,
                         trend["timestamp"], trend["load_kw"], "Load (kW)",
                         "Load Trend (surrounding window)", "#fb923c")

        # Risk-over-time: run the model across the same window
        risk_series = model.predict_proba(trend[feature_cols])[:, 1] * 100
        self.ax_risk.clear()
        self.ax_risk.plot(trend["timestamp"], risk_series, color="#f87171", linewidth=2, label="Risk %")
        self.ax_risk.fill_between(trend["timestamp"], risk_series, alpha=0.15, color="#f87171")
        self.ax_risk.axhline(70, color="#ef4444", linestyle="--", linewidth=1, alpha=0.6)
        self._style_ax(self.ax_risk, "Predicted Risk % Over Time (surrounding window)")
        self.ax_risk.legend(facecolor=CARD_COLOR, labelcolor="white", fontsize=8, frameon=False)
        self.fig_risk.autofmt_xdate(rotation=20)
        self.fig_risk.tight_layout()
        self.canvas_risk.draw()

    def _draw_line(self, ax, fig, canvas, x, y, label, title, color):
        ax.clear()
        ax.plot(x, y, color=color, linewidth=2, label=label)
        ax.fill_between(x, y, alpha=0.1, color=color)
        self._style_ax(ax, title)
        ax.legend(facecolor=CARD_COLOR, labelcolor="white", fontsize=8, frameon=False)
        fig.autofmt_xdate(rotation=20)
        fig.tight_layout()
        canvas.draw()


if __name__ == "__main__":
    app = PowerPulseApp()
    app.mainloop()
